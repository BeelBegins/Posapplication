import type { ApiClient } from "./client";

export function createHrApi(client: ApiClient) {
  const post = (name: string, body: Record<string, unknown> = {}) => client.callMethod(`aimatichr.hr_mobile.api.${name}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const ss = (name: string, body: Record<string, unknown> = {}) => client.callMethod(`aimatichr.hr_mobile.selfservice.${name}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const ops = (name: string, body: Record<string, unknown> = {}) => client.callMethod(`aimatichr.hr_mobile.hrops.${name}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const tal = (name: string, body: Record<string, unknown> = {}) => client.callMethod(`aimatichr.hr_mobile.talent.${name}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  return {
    // Phase 4 hiring (aimatichr.hr_mobile.hiring)
    getOpenings: () => client.callMethod("aimatichr.hr_mobile.hiring.get_openings", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" }),
    getPipeline: (body: { opening: string }) => client.callMethod("aimatichr.hr_mobile.hiring.get_pipeline", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    getApplicant: (body: { name: string }) => client.callMethod("aimatichr.hr_mobile.hiring.get_applicant", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    getResume: (body: { name: string }) => client.callMethod("aimatichr.hr_mobile.hiring.get_resume", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    moveApplicant: (body: { name: string; stage: string; note?: string }) => client.callMethod("aimatichr.hr_mobile.hiring.move_applicant", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    addApplicantNote: (body: { name: string; note: string }) => client.callMethod("aimatichr.hr_mobile.hiring.add_applicant_note", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    addToPool: (body: { name: string; pool: string; note?: string }) => client.callMethod("aimatichr.hr_mobile.hiring.add_to_pool", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    // Phase 4 surveys (aimatichr.hr_mobile.surveys)
    getSurveys: () => client.callMethod("aimatichr.hr_mobile.surveys.get_surveys", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" }),
    getSurvey: (body: { name: string }) => client.callMethod("aimatichr.hr_mobile.surveys.get_survey", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    submitSurvey: (body: { name: string; answers: Record<string, unknown> }) => client.callMethod("aimatichr.hr_mobile.surveys.submit_survey", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    // Phase 4 talent (aimatichr.hr_mobile.talent)
    getGoals: () => tal("get_goals"),
    goalCheckIn: (body: { goal: string; progress: number; confidence?: string; note?: string }) => tal("goal_check_in", body),
    getOneOnOnes: () => tal("get_one_on_ones"),
    getOneOnOne: (body: { name: string }) => tal("get_one_on_one", body),
    scheduleOneOnOne: (body: { scheduled_on: string; agenda?: string; employee?: string }) => tal("schedule_one_on_one", body),
    updateOneOnOne: (body: Record<string, unknown>) => tal("update_one_on_one", body),
    getPoints: () => tal("get_points"),
    searchColleagues: (body: { query?: string }) => tal("search_colleagues", body),
    givePoints: (body: { employee: string; points: number; reason: string; category?: string }) => tal("give_points", body),
    requestRedemption: (body: { points: number; note?: string }) => tal("request_redemption", body),
    // Phase 3 HR operations (aimatichr.hr_mobile.hrops)
    getHelp: (body: { query?: string }) => ops("get_help", body),
    createTicket: (body: Record<string, unknown>) => ops("create_ticket", body),
    getTicket: (body: { name: string }) => ops("get_ticket", body),
    addTicketComment: (body: { name: string; message: string }) => ops("add_ticket_comment", body),
    ticketAction: (body: Record<string, unknown>) => ops("ticket_action", body),
    getPolicies: () => ops("get_policies"),
    getPolicy: (body: { name: string }) => ops("get_policy", body),
    getPolicyAttachment: (body: { name: string }) => ops("get_policy_attachment", body),
    acknowledgePolicy: (body: { name: string; policy_version: number }) => ops("acknowledge_policy", body),
    getDocumentRequests: () => ops("get_document_requests"),
    createLetterRequest: (body: Record<string, unknown>) => ops("create_letter_request", body),
    uploadRequestedDocument: (body: Record<string, unknown>) => ops("upload_requested_document", body),
    getIssuedLetter: (body: { name: string }) => ops("get_issued_letter", body),
    getAssets: () => ops("get_assets"),
    createAssetRequest: (body: Record<string, unknown>) => ops("create_asset_request", body),
    getDisciplinary: () => ops("get_disciplinary"),
    respondDisciplinary: (body: Record<string, unknown>) => ops("respond_disciplinary", body),
    getLoans: () => ops("get_loans"),
    // Phase 2 self-service (aimatichr.hr_mobile.selfservice)
    actOnApproval: (body: Record<string, unknown>) => ss("act_on_approval", body),
    getExpenses: () => ss("get_expenses"),
    getExpenseOptions: () => ss("get_expense_options"),
    createExpenseClaim: (body: Record<string, unknown>) => ss("create_expense_claim", body),
    createEmployeeAdvance: (body: Record<string, unknown>) => ss("create_employee_advance", body),
    cancelLeaveApplication: (body: { name: string }) => ss("cancel_leave_application", body),
    getPayslipPdf: (body: { name: string }) => ss("get_payslip_pdf", body),
    getNotifications: () => ss("get_notifications"),
    markNotificationsRead: (body: { name?: string }) => ss("mark_notifications_read", body),
    getProfile: () => ss("get_profile"),
    updateProfile: (body: { updates: Record<string, string> }) => ss("update_profile", body),
    getDocuments: () => ss("get_documents"),
    uploadDocument: (body: Record<string, unknown>) => ss("upload_document", body),
    getContext: () => post("get_context"),
    getLeaveSummary: () => post("get_leave_summary"),
    getPayslips: () => post("get_payslips"),
    getDirectory: (query = "") => post("get_directory", { query }),
    getTeam: () => post("get_team"),
    getRequests: () => post("get_requests"),
    getApprovals: () => post("get_approvals"),
    getRecentCheckins: () => post("get_recent_checkins"),
    getAttendanceCalendar: (month: string) => post("get_attendance_calendar", { month }),
    getCheckinLocation: () => post("get_checkin_location"),
    getFormOptions: () => post("get_form_options"),
    requestCheckinChallenge: () => post("request_checkin_challenge"),
    submitAttendance: (body: Record<string, unknown>) => post("submit_attendance", body),
    createLeaveApplication: (body: Record<string, unknown>) => post("create_leave_application", body),
    createAttendanceRequest: (body: Record<string, unknown>) => post("create_attendance_request", body),
    getFacePolicy: () => post("get_face_policy"),
    enrollFace: (body: Record<string, unknown>) => post("enroll_face", body),
    revokeFace: (body: Record<string, unknown>) => post("revoke_face", body),
  };
}
